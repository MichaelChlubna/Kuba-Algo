"""Golden outputs: the sample dataset run through the pipeline and the API.

`python -m tests.golden_util` (in backend/) regenerates tests/golden/*.parquet. The stored files were
generated by the original application (commit 221e88e code moved to backend/, unchanged), so
test_golden.py checks that the web version computes the same candles, features, footprint, POC,
imbalances and API responses on the same data (float tolerance only for summation order).
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path

import polars as pl

GOLDEN = Path(__file__).resolve().parent / "golden"
DAYS = (dt.date(2026, 10, 1), dt.date(2026, 10, 3))
D2 = 1_790_899_200_000  # 2026-10-02 00:00 UTC
DAY = 86_400_000
H = 3_600_000


def build_sample(root: Path) -> dict:
    from fp.build import build
    from fp.config import load_config
    from fp.sample import write_sample

    cfg = load_config()
    cfg["paths"] = {"raw": root / "raw", "parquet": root / "parquet", "derived": root / "derived"}
    write_sample(cfg, *DAYS)
    build(cfg, *DAYS)
    return cfg


def _frame(js: dict) -> pl.DataFrame:
    df = pl.DataFrame(js["cols"]) if js["n"] else pl.DataFrame()
    return df.select(sorted(df.columns))


def compute(cfg: dict) -> dict[str, pl.DataFrame]:
    """name -> frame: derived files of day 2 (1m footprint: 2 hours) and API responses."""
    from fastapi.testclient import TestClient
    from fp.server import create_app

    out = {}
    derived = cfg["paths"]["derived"]
    for kind in ("series", "footprint"):
        for d in sorted((derived / kind).iterdir()):
            df = pl.read_parquet(d / "2026-10-02.parquet")
            if kind == "footprint" and d.name == "1m":
                df = df.filter((pl.col("start_ts") >= D2 + 12 * H) & (pl.col("start_ts") < D2 + 14 * H))
            sort = ["cid" if "cid" in df.columns else "start_ts"] + (["level"] if kind == "footprint" else [])
            out[f"{kind}_{d.name}"] = df.select(sorted(df.columns)).sort(sort)
    c = TestClient(create_app(cfg))
    q = {
        "api_candles_5m": f"/api/candles?agg=5m&start={D2}&end={D2 + DAY}&pad=20",
        "api_candles_1m_full": f"/api/candles?agg=1m&start={D2 + 12 * H}&end={D2 + 14 * H}&full=1",
        "api_candles_vusd": f"/api/candles?agg=vusd_100000000&start={D2}&end={D2 + DAY}&full=1",
        "api_candle_15m": f"/api/candle?agg=15m&cid={D2 + 36 * 900_000}&start_ts={D2 + 36 * 900_000}",
        "api_footprint_5m": f"/api/footprint?agg=5m&start={D2 + 12 * H}&end={D2 + 16 * H}",
        "api_footprint_vbtc": f"/api/footprint?agg=vbtc_1000&start={D2}&end={D2 + DAY}",
    }
    for name, url in q.items():
        r = c.get(url)
        assert r.status_code == 200, (url, r.text)
        out[name] = _frame(r.json())
    r = c.get(f"/api/periods?start={D2}&end={D2 + DAY}&tz=America/New_York&bin=25")
    assert r.status_code == 200, r.text
    out["api_periods"] = _frame(r.json()["periods"])
    out["api_periods_levels"] = _frame(r.json()["levels"])
    return out


if __name__ == "__main__":
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        res = compute(build_sample(Path(tmp)))
    GOLDEN.mkdir(parents=True, exist_ok=True)
    for name, df in res.items():
        df.write_parquet(GOLDEN / f"{name}.parquet", compression="zstd", compression_level=19)
    print(f"wrote {len(res)} golden files to {GOLDEN}")
